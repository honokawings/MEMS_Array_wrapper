"""Freeze deterministic BIST stimulus and a bit-exact periodic PCM oracle."""
from common import *
import fixed
import hashlib
import json
import subprocess


def main():
    out=ROOT/'tb/vectors'; out.mkdir(exist_ok=True)
    n=np.arange(16384,dtype=np.int64)[:,None]
    c=np.arange(128,dtype=np.int64)[None,:]
    reverse=np.zeros_like(n)
    for bit in range(8): reverse|=((n>>bit)&1)<<(7-bit)
    threshold=64+c+np.where((((n>>8)+c)&2)!=0,16,-16)
    pdm=(reverse<threshold).astype(np.uint8)
    packed=np.packbits(pdm,axis=1,bitorder='little')
    (out/'selftest_pdm.bin').write_bytes(packed.tobytes())
    (out/'selftest_pdm.hex').write_text(''.join(row.tobytes()[::-1].hex()+'\n' for row in packed[:1024]))
    pcm=fixed.process(pdm)[3]
    (out/'selftest_calibration.txt').write_text('4194304 0\n'*128)
    subprocess.run([str(ROOT/'log/build/mems_rm.exe'),str(out/'selftest_pdm.bin'),
                    str(ROOT/'lib/coeff'),str(out/'selftest_expected'),str(out/'selftest_calibration.txt')],check=True)
    cpp=np.fromfile(out/'selftest_expected_pcm.bin',dtype='<i4').reshape(-1,128)
    assert np.array_equal(pcm,cpp), 'Independent C++ model mismatch'
    period=pcm[96:112]
    assert all(np.array_equal(pcm[start:start+16],period) for start in range(112,256,16))
    assert len({tuple(period[:,ch]) for ch in range(128)})==128
    rom='// Generated by lib/model/generate_selftest.py; frame_id modulo 16, then channel.\n'
    rom+=''.join(f"expected_rom[{i}]=24'h{int(value)&0xffffff:06x};\n" for i,value in enumerate(period.flat))
    (ROOT/'rtl/selftest_expected.svh').write_text(rom,encoding='ascii')
    data=b''.join((int(value)&0xffffff).to_bytes(3,'little') for value in period.flat)
    (ROOT/'lib/host/selftest_pcm.bin').write_bytes(data)
    (out/'selftest_pcm.hex').write_text(''.join(''.join(f'{int(v)&0xffffff:06x}' for v in row[::-1])+'\n' for row in pcm))
    result={'status':'PASS','pattern_id':1,'pdm_period':1024,'pcm_period':16,'first_valid_frame':96,
            'channels':128,'samples_compared':int(pcm.size),'distinct_channels':128,
            'pcm_period_sha256':hashlib.sha256(data).hexdigest()}
    (out/'selftest_manifest.json').write_text(json.dumps(result,indent=2)+'\n')
    print('[MODEL_INFO] BIST Python/C++ exact, 32768 samples, 128 distinct channels, periodic steady-state PASS')


if __name__=='__main__':main()
